export function translateStorefront(key: keyof typeof STOREFRONT_TRANSLATIONS['ar'], lang: Locale, count?: number): string {
  const dict = STOREFRONT_TRANSLATIONS[lang] || STOREFRONT_TRANSLATIONS['ar'];
  let text = dict[key] || STOREFRONT_TRANSLATIONS['ar'][key] || '';
  if (count !== undefined) {
    text = text.replace('{count}', String(count));
  }
  return text;
}

